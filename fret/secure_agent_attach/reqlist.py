"""Readable list of the requirements that are given to FRET.

``docs/REQUIREMENTS.md`` lists every FRETish sentence of the project,
grouped by what it asks for: the security requirements and the
functional specification of the core catalog, the requirements of the
turn state machine, the tool-call monitor and the functional
requirements added for its realizability check.  The list is built from
the requirement files only; results of checks are in
``docs/CORE_SPEC.md``.
"""

from __future__ import annotations

import json

from . import fret_nusmv as fn
from . import spec as sp

OUT = fn.ROOT / "docs" / "REQUIREMENTS.md"
ATTACKS = {
    "authorization": "privilege escalation",
    "exfiltration": "exfiltration chain",
    "resources": "resource exhaustion",
    "completion": "false completion",
}


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _code(text: str) -> str:
    return "`" + _cell(text) + "`"


def _load(name: str) -> dict:
    path = fn.ROOT / "requirements" / name
    return json.loads(path.read_text(encoding="utf-8"))


def _table(head: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(head) + " |"]
    out.append("|" + "---|" * len(head))
    out.extend("| " + " | ".join(row) + " |" for row in rows)
    return out + [""]


def _original(req: dict) -> str:
    if req["asis"] == "ok":
        return "complies"
    return "violates: " + _cell(req["asis_desc"])


def _intro(spec: dict, reqs: list[dict]) -> list[str]:
    example = next(r for r in reqs if r["id"] == "GATE-03")
    sec = sum(r["kind"] == "SEC" for r in reqs)
    return [
        "# Requirements given to FRET",
        "",
        "Generated by `python -m secure_agent_attach doc` from the files "
        "in `requirements/`. Do not edit.",
        "",
        "## How to read",
        "",
        "Every requirement is one sentence in FRETish, the structured "
        "English of FRET. FRET's parser turns the sentence into a "
        "temporal-logic formula, which is then checked by NuSMV and "
        "Kind2. A sentence names a component (the part of the system "
        "that must behave), says when the requirement holds and what the "
        "component must satisfy. Here every requirement holds at every "
        "step (`always`, or `never` for a forbidden event). The "
        "conditions are made of signals; a signal is either chosen by "
        "the environment (Input) or decided by the system (Output).",
        "",
        "Example, requirement GATE-03:",
        "",
        f"- Sentence: {_code(example['text'])}",
        f"- Meaning: {example['desc']}.",
        "",
        "`{NAME}` in a sentence is a shorthand for a longer condition. "
        "The expressions are in the macro table at the end. "
        "`SEC` marks a security requirement, `FUN` a statement of what "
        "the code does. \"Original\" tells whether the unmodified "
        "Secure_Agent already satisfies the requirement.",
        "",
        "## Overview",
        "",
        *_table(
            ["Group", "Requirements", "Source"],
            [
                [
                    "Security requirements of the core",
                    str(sec),
                    "`requirements/core_spec.json`",
                ],
                [
                    "Functional specification of the core",
                    str(len(reqs) - sec),
                    "`requirements/core_spec.json`",
                ],
                [
                    "Turn state machine",
                    str(len(_load("core_requirements.json")["requirements"])),
                    "`requirements/core_requirements.json`",
                ],
                [
                    "Tool-call monitor",
                    str(len(_load("call_requirements.json")["requirements"])),
                    "`requirements/call_requirements.json`",
                ],
                [
                    "Realizability of the monitor",
                    str(len(_load("call_realizability.json")["requirements"])),
                    "`requirements/call_realizability.json`",
                ],
            ],
        ),
    ]


def _security(spec: dict, reqs: list[dict]) -> list[str]:
    by_id = {r["id"]: r for r in reqs}
    out = [
        "## Security requirements of the core",
        "",
        "Grouped by security function. A requirement belongs to one "
        "function; the component says which part of `core.py` it "
        "constrains.",
        "",
    ]
    for sf in spec["security_functions"]:
        out += [f"### {sf['id']} {sf['name']}", "", sf["desc"], ""]
        rows = []
        for rid in sf["reqs"]:
            r = by_id[rid]
            rows.append(
                [
                    r["id"],
                    r["component"],
                    _code(r["text"]),
                    _cell(r["desc"]),
                    _original(r),
                ]
            )
        out += _table(
            ["ID", "Component", "FRETish", "Meaning", "Original"], rows
        )
    return out


def _functional(spec: dict, reqs: list[dict]) -> list[str]:
    out = [
        "## Functional specification of the core",
        "",
        "What each part of `core.py` does, one table per component.",
        "",
    ]
    for cname, comp in spec["components"].items():
        rows = [
            [
                r["id"],
                _code(r["text"]),
                _cell(r["desc"]),
                _original(r),
            ]
            for r in reqs
            if r["component"] == cname and r["kind"] == "FUN"
        ]
        if not rows:
            continue
        out += [f"### {cname}: {comp['title']}", ""]
        out += _table(["ID", "FRETish", "Meaning", "Original"], rows)
    return out


def _state_machine() -> list[str]:
    doc = _load("core_requirements.json")
    rows = [
        [r["id"], _cell(r["title"]), _code(r["fretish"]), _cell(r["why"])]
        for r in doc["requirements"]
    ]
    return [
        "## Turn state machine",
        "",
        "Eight requirements on the turn loop, checked with NuSMV on a "
        "model of `process_turn` and on end-to-end scenarios.",
        "",
        *_table(["ID", "Title", "FRETish", "Why"], rows),
    ]


def _monitor() -> list[str]:
    doc = _load("call_requirements.json")
    rows = [
        [
            r["id"],
            ATTACKS[r["class"]],
            _cell(r["title"]),
            _code(r["fretish"]),
            _cell(r["why"]),
        ]
        for r in doc["requirements"]
    ]
    return [
        "## Tool-call monitor",
        "",
        "The model is treated as an attacker. Each requirement states a "
        "line that must hold whatever the model does.",
        "",
        *_table(["ID", "Attack", "Title", "FRETish", "Why"], rows),
    ]


def _realizability() -> list[str]:
    doc = _load("call_realizability.json")
    rows = [
        [
            r["id"],
            "safety" if r["id"].startswith("CM-") else "functional",
            _code(r["text"]),
        ]
        for r in doc["requirements"]
    ]
    return [
        "## Realizability of the monitor",
        "",
        "The safety requirements alone are met by a monitor that does "
        "nothing. For the realizability check they are written over "
        "per-tool signals and complemented by functional requirements "
        "that say what an allowed call must cause.",
        "",
        *_table(["ID", "Kind", "FRETish"], rows),
    ]


def _macros(spec: dict) -> list[str]:
    rows = [
        [cname, "`{" + name + "}`", _code(expr)]
        for cname, comp in spec["components"].items()
        for name, expr in (comp.get("macros") or {}).items()
    ]
    return [
        "## Macros",
        "",
        "Shorthands used in the sentences of the core catalog.",
        "",
        *_table(["Component", "Name", "Expression"], rows),
    ]


def write() -> None:
    """Write ``docs/REQUIREMENTS.md`` from the requirement files."""
    spec = sp.load()
    reqs = sp.requirements(spec)
    lines = (
        _intro(spec, reqs)
        + _security(spec, reqs)
        + _functional(spec, reqs)
        + _state_machine()
        + _monitor()
        + _realizability()
        + _macros(spec)
    )
    OUT.write_text("\n".join(lines).rstrip("\n") + "\n", encoding="utf-8")
